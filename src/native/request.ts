import type { FetchRequestMessage, FormDataEntry } from '../shared/protocol';
import { base64ToArrayBuffer } from '../shared/base64';
import { isReactNative } from './env';

type FileEntry = Extract<FormDataEntry, { filename: string }>;

function appendFile(fd: FormData, entry: FileEntry): void {
  if (isReactNative()) {
    // RN's Blob cannot be built from bytes, but its FormData accepts `{ uri, name, type }`
    // parts and both platforms' networking stacks read `data:` URIs natively.
    fd.append(entry.name, {
      uri: `data:${entry.contentType};base64,${entry.data}`,
      name: entry.filename,
      type: entry.contentType,
    } as unknown as Blob);
    return;
  }
  const blob = new Blob([base64ToArrayBuffer(entry.data)], { type: entry.contentType });
  fd.append(entry.name, blob, entry.filename);
}

/** Rebuilds the body and headers of a `FETCH_REQUEST` for the native `fetch`. */
export function buildNativeBody(req: FetchRequestMessage): { body: BodyInit | undefined; headers: Record<string, string> } {
  const headers: Record<string, string> = {};
  for (const key in req.headers ?? {}) headers[key.toLowerCase()] = req.headers[key];

  if (req.bodyType === 'formdata') {
    const fd = new FormData();
    for (const entry of req.formDataEntries ?? []) {
      if ('filename' in entry) appendFile(fd, entry);
      else fd.append(entry.name, entry.value);
    }
    // The multipart boundary is generated by the native fetch.
    delete headers['content-type'];
    return { body: fd, headers };
  }

  if (req.body === null || req.body === undefined) return { body: undefined, headers };
  if (req.bodyType === 'base64') return { body: base64ToArrayBuffer(req.body), headers };
  return { body: req.body, headers };
}
